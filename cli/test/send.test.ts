import assert from "node:assert/strict";
import { test } from "node:test";
import { sendFilename, sendTargetNote, sendText } from "../ui/send-text.js";

test("says before sending whether a model is hosted, and which is in use", () => {
	const base = { id: "x", label: "m · somewhere", model: "m", host: "api.anthropic.com", hosted: true, current: false };
	assert.equal(sendTargetNote(base), "Leaves this computer: sent to api.anthropic.com.");
	assert.equal(sendTargetNote({ ...base, hosted: false, host: "localhost:11434", current: true }), "In use for Explain and Ask. Stays with your own model at localhost:11434.");
});

test("heads copied or saved text with what wrote it, and names files from a fixed stem and the date", () => {
	const text = sendText("  Step 1.  ", { model: "m", label: "m · Claude", content: "roadmap", purpose: "repair", notes: [undefined, "Only part fit."], scannedAt: "2026-11-19T07:00:00Z" });
	assert.equal(
		text,
		"Repair plan of the repair roadmap, generated by m · Claude.\nFrom the SecurityX scan of 2026-11-19T07:00:00Z. Written by a model: check it against the findings before acting on it.\nOnly part fit.\n\nStep 1.\n",
	);
	assert.equal(sendFilename("repair", "2026-11-19T07:00:00Z"), "securityx-repair-plan-2026-11-19.txt");
	assert.equal(sendFilename("analyse", "../../etc"), "securityx-analysis-undated.txt");
});

test("names a finding the same way across scans, and words a change and a status", async () => {
	const { changeSummary, findingKey, isStatus, statusLabel } = await import("../ui/tracking.js");
	assert.equal(findingKey("repo", { ruleId: "GHSA-1", location: "go.mod", detail: "x@1" }), "repo\nGHSA-1\ngo.mod\nx@1");
	assert.equal(changeSummary(null), null);
	assert.equal(changeSummary({ previousScannedAt: "", newCount: 0, fixedCount: 0 }), "Nothing new and nothing fixed since the previous scan.");
	assert.equal(changeSummary({ previousScannedAt: "", newCount: 2, fixedCount: 1200 }), "2 new, 1,200 fixed since the previous scan.");
	assert.deepEqual([isStatus("accepted"), isStatus("ignored"), statusLabel("false-positive")], [true, false, "False positive"]);
});
