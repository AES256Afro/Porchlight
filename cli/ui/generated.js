// @ts-check
// How the page words and shapes what the local model writes. No DOM here, so it is tested directly.

/**
 * What `/api/state` says about the local model. `unset`: no model address was given, so the
 * features are simply off, as opposed to a setting to correct.
 *
 * @typedef {{ configured: boolean, model?: string, host?: string, hosted?: boolean, error?: string, unset?: boolean }} AssistantSettings
 */

/** The longest question the server takes, in characters. */
export const MAX_QUESTION = 500;

/** The model the BoxPilot app suggests, named the way Ollama names it. */
export const SUGGESTED_MODEL = "hf.co/hauhaucs/qwen3.5-9b-uncensored-hauhaucs-aggressive:Q4_K_M";

/**
 * Generated text as paragraphs, split on blank lines. A single line break stays inside its
 * paragraph, where the page keeps it, so a list the model wrote still reads as a list.
 *
 * @param {string} text
 * @returns {string[]}
 */
export function paragraphs(text) {
	return text
		.replace(/\r\n?/g, "\n")
		.split(/\n[ \t]*\n/)
		.map((paragraph) => paragraph.replace(/^(?:[ \t]*\n)+/, "").trimEnd())
		.filter((paragraph) => paragraph.trim() !== "");
}

/** @param {string} model */
export function generatedLabel(model) {
	return `Generated by ${model}. Check it against the findings.`;
}

/** @param {string} model */
export function waitingLabel(model) {
	return `Asking ${model}… this can take a few minutes without a graphics card.`;
}

/**
 * What is wrong with a question before it is sent, or null when nothing is.
 *
 * @param {string} question
 * @returns {string | null}
 */
export function questionProblem(question) {
	if (question.trim() === "") return "Write a question first.";
	if (question.length > MAX_QUESTION) return `Keep the question to ${MAX_QUESTION} characters. It has ${question.length.toLocaleString()}.`;
	return null;
}

/**
 * How to connect a model, in the terms of where Porchlight runs: on this computer, Settings → Model;
 * as a service (a container, under BoxPilot), the app's settings.
 * Steps mark names to type with backticks, as suggested fixes do.
 *
 * @param {AssistantSettings | null | undefined} assistant
 * @param {boolean} service
 * @returns {{ reason: string | null, steps: string[], commands: string | null }}
 */
export function localModelSetup(assistant, service) {
	// Nothing given yet is the usual state, not a mistake to quote back.
	const reason = assistant?.unset ? null : (assistant?.error ?? null);
	if (service) {
		return {
			reason,
			steps: [
				`Install the Ollama app in BoxPilot, and add the model \`${SUGGESTED_MODEL}\` in its Models tab.`,
				"In BoxPilot, open Apps → Porchlight → Settings and fill in Local model address and Local model.",
			],
			commands: null,
		};
	}
	return {
		reason,
		steps: [
			"Open Settings → Model and choose where your model runs: Ollama, Unsloth Studio or LM Studio on this computer, a model server of your own, or the Claude, ChatGPT, Gemini or DeepSeek API.",
		],
		commands: null,
	};
}

/** How each of the model's verdicts on a finding is worded, and how they order: most pressing first. */
export const VERDICT_LABELS = /** @type {const} */ ({
	confirmed: "Model: confirmed",
	likely: "Model: likely real",
	unclear: "Model: unclear",
	unlikely: "Model: unlikely to matter",
});

const VERDICT_ORDER = Object.keys(VERDICT_LABELS);

/**
 * Where a finding sorts by the model's verdict. One the model has not judged goes after those it
 * has, and "unlikely" goes last of all: a sort, never a filter, so nothing is hidden by it.
 *
 * @param {{ analysis?: { verdict: string } } | undefined} finding
 */
export function verdictRank(finding) {
	const verdict = finding?.analysis?.verdict;
	if (verdict === undefined) return 3;
	if (verdict === "unlikely") return 4;
	const index = VERDICT_ORDER.indexOf(verdict);
	return index === -1 ? 3 : index;
}

/**
 * What the analysis has covered, in a sentence.
 *
 * @param {{ items: number, judged: number, waiting: Record<string, number> } | null | undefined} summary
 */
export function analysisProgress(summary) {
	if (!summary) return "";
	const urgent = (summary.waiting.critical ?? 0) + (summary.waiting.high ?? 0);
	const left = summary.items - summary.judged;
	if (left === 0) return `The model has judged all ${summary.items.toLocaleString()} items of this scan.`;
	return `The model has judged ${summary.judged.toLocaleString()} of ${summary.items.toLocaleString()} items. ${urgent.toLocaleString()} critical or high ${urgent === 1 ? "one is" : "ones are"} waiting.`;
}

/**
 * What starting an analysis sends, and where, said before it is sent.
 *
 * @param {AssistantSettings} assistant
 */
export function analysisNotice(assistant) {
	const what = "For each finding it is sent the finding as shown here and, for a vulnerable package, the lines of your code that import it. Secret values are never sent, and no file content is sent for a leaked secret.";
	return assistant.hosted
		? `This sends that to ${assistant.host}, outside your own machines, under your API key, and each item is billed to it. ${what}`
		: `${what} It goes to your own model at ${assistant.host}.`;
}
