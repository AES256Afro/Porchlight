// @ts-check
// How "Send to a model" words its choices and the text it copies or saves. No DOM here, so it is tested directly.

/**
 * A model "Send to a model" offers, as `/api/state` describes it. `id` is SecurityX's own.
 *
 * @typedef {{ id: string, label: string, model: string, host: string, hosted: boolean, current: boolean }} SendTarget
 */

/**
 * Said under a model's name: whether it is the one in use, and, before anything is sent, whether
 * what is sent leaves the owner's machines.
 *
 * @param {SendTarget} target
 */
export function sendTargetNote(target) {
	const where = target.hosted ? `Leaves this computer: sent to ${target.host}.` : `Stays with your own model at ${target.host}.`;
	return target.current ? `In use for Explain and Ask. ${where}` : where;
}

const PURPOSE_NAMES = /** @type {Record<string, string>} */ ({ analyse: "Deeper analysis", repair: "Repair plan" });
const CONTENT_NAMES = /** @type {Record<string, string>} */ ({ roadmap: "the repair roadmap", findings: "the findings" });

/**
 * The answer as plain text to copy or save, headed with what wrote it and from what, so it is never
 * mistaken for SecurityX's own findings.
 *
 * @param {string} text
 * @param {{ model: string, label: string, content: string, purpose: string, notes: (string | undefined)[], scannedAt: string }} about
 */
export function sendText(text, about) {
	const head = [
		`${PURPOSE_NAMES[about.purpose] ?? "Answer"} of ${CONTENT_NAMES[about.content] ?? "the scan"}, generated by ${about.label}.`,
		`From the SecurityX scan of ${about.scannedAt || "an unknown date"}. Written by a model: check it against the findings before acting on it.`,
		...about.notes.filter((note) => note),
	];
	return `${head.join("\n")}\n\n${text.trim()}\n`;
}

/**
 * A fixed stem and the scan's date, never anything a model or a scan wrote.
 *
 * @param {string} purpose
 * @param {string} scannedAt
 */
export function sendFilename(purpose, scannedAt) {
	const day = /^\d{4}-\d{2}-\d{2}/.exec(scannedAt)?.[0] ?? "undated";
	return `securityx-${purpose === "repair" ? "repair-plan" : "analysis"}-${day}.txt`;
}
