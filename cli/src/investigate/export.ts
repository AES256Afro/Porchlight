/**
 * One investigation as a file: Markdown to read, or JSON to keep. Everything in it came from the
 * target or from the model, so it is escaped for the format (invariant 11). Set-Cookie values are
 * left out; the rest of each exchange is kept as evidence. The name is a fixed stem and a date.
 */
import { mdBlock, mdCode, mdText } from "../roadmap/escape.ts";
import { withoutCookieValues, type Run } from "./engine.ts";

export const INVESTIGATION_FORMATS = ["md", "json"] as const;
export type InvestigationFormat = (typeof INVESTIGATION_FORMATS)[number];

export interface InvestigationFile {
	filename: string;
	contentType: string;
	body: string;
}

const STATUS_WORDS: Record<string, string> = { open: "not reviewed", accepted: "accepted by you", dismissed: "dismissed by you" };

export function exportInvestigation(run: Run, format: InvestigationFormat): InvestigationFile {
	const stem = `porchlight-investigation-${run.startedAt.slice(0, 10).replace(/[^0-9-]/g, "")}`;
	if (format === "json") {
		const redacted = { ...run, evidence: run.evidence.map((evidence) => ({ ...evidence, response: withoutCookieValues(evidence.response) })) };
		return { filename: `${stem}.json`, contentType: "application/json; charset=utf-8", body: `${JSON.stringify(redacted, null, "\t")}\n` };
	}
	return { filename: `${stem}.md`, contentType: "text/markdown; charset=utf-8", body: markdown(run) };
}

/** How the run's HTTP requests and TCP connections were approved, in words: Porchlight's own, from its own record. */
export function approvalWords(run: Pick<Run, "approvedRest">): string {
	if (!run.approvedRest) return "you approved each HTTP request and TCP connection before it was sent";
	return run.approvedRest.turn === 0
		? "you approved every HTTP request and TCP connection when the run started"
		: `you approved each HTTP request and TCP connection up to turn ${run.approvedRest.turn}, and at that turn every later one`;
}

function markdown(run: Run): string {
	const out: string[] = [];
	out.push(`# Investigation of ${mdText(run.domain)}`, "");
	out.push(`- Goal: ${mdText(run.goal)}`);
	out.push(`- Model: ${mdText(run.model)}${run.hosted ? " (hosted: what it read left this computer)" : ""}`);
	out.push(`- Started: ${mdText(run.startedAt)}${run.finishedAt ? `, ended ${mdText(run.finishedAt)}` : ""}`);
	out.push(`- Status: ${mdText(run.status)}${run.ended ? `. ${mdText(run.ended)}` : ""}`);
	out.push(`- Turns: ${run.turns} of ${run.maxTurns}; actions run: ${run.evidence.length}`);
	out.push(`- Approval: ${approvalWords(run)}`);
	if (run.status === "running" || run.status === "waiting") out.push("- **This investigation had not finished when it was exported.**");
	out.push("");
	out.push(
		`> Findings below are the model's judgement, generated by ${mdText(run.model)}. Each cites the evidence it rests on; check it there. They do not change any scan's severities, counts or roadmap.`,
		"",
	);

	out.push("## Findings", "");
	if (run.findings.length === 0) out.push("The model reported no finding backed by evidence.", "");
	for (const finding of run.findings) {
		out.push(`### ${mdText(finding.title)}`, "");
		out.push(`- Model's severity: ${mdText(finding.severity)}`);
		out.push(`- Your review: ${STATUS_WORDS[finding.status] ?? "not reviewed"}`);
		if (finding.asset) out.push(`- Host: ${mdCode(finding.asset)}`);
		out.push(`- Evidence: ${finding.evidenceIds.map(mdCode).join(", ")}`, "");
		if (finding.description) out.push(mdText(finding.description), "");
	}
	if (run.discarded > 0) out.push(`${run.discarded} further finding${run.discarded === 1 ? "" : "s"} cited no real evidence and ${run.discarded === 1 ? "was" : "were"} discarded.`, "");

	if (run.summary) out.push("## The model's summary", "", mdText(run.summary), "");

	out.push("## Steps", "");
	for (const step of run.steps) {
		const what = step.description ? mdCode(step.description) : step.tool ? mdCode(`${step.tool} ${JSON.stringify(step.args ?? {})}`) : mdText(step.outcome);
		const approved = step.approvedBy === "run" ? ", under your approval of the whole run" : step.approvedBy === "owner" ? ", approved by you" : "";
		out.push(`${step.turn}. ${what}: ${mdText(step.outcome)}${approved}${step.reason ? `. ${mdText(step.reason)}` : ""}${step.evidenceId ? ` (evidence ${mdCode(step.evidenceId)})` : ""}`);
		if (step.thought) out.push(`   - Model's reasoning: ${mdText(step.thought)}`);
	}
	out.push("");

	out.push("## Evidence", "");
	for (const evidence of run.evidence) {
		out.push(`### ${mdCode(evidence.id)}: ${mdText(evidence.tool)}`, "", `Captured ${mdText(evidence.at)}.`, "", "Request:", "", mdBlock(evidence.request), "", "Response:", "", mdBlock(withoutCookieValues(evidence.response)), "");
	}
	return `${out.join("\n")}\n`;
}
