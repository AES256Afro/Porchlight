#!/usr/bin/env node
// Writes cli/src/repos/gitleaks.toml: gitleaks' built-in rules, as the gitleaks on PATH (or the
// binary named on the command line) carries them, with its global path allowlist reduced to `.git`.
//
// Why: gitleaks' default config skips whole files by name before any rule runs: lockfiles, go.sum,
// *.svg, *.pdf, bootstrap*.js, venv/lib and more. A real key committed in one of them was never
// reported, and nothing said so (S53 in docs/AUDIT-PLAN-2026-11-20.md). Porchlight reports what is in
// those files and lets triage rank it (invariant 10); it never filters by path.
//
// The rules are read from the binary itself (gitleaks embeds its default config as text), so nothing is
// downloaded and the rules match the gitleaks Porchlight is tested with. Run again after upgrading
// gitleaks: node scripts/vendor-gitleaks-rules.mjs [path/to/gitleaks]
import { execFileSync } from "node:child_process";
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const binary = realpathSync(process.argv[2] ?? execFileSync("sh", ["-c", "command -v gitleaks"], { encoding: "utf8" }).trim());
const version = execFileSync(binary, ["version"], { encoding: "utf8" }).trim();
const bytes = readFileSync(binary).toString("latin1");

const start = bytes.indexOf("# This file has been auto-generated");
if (start < 0) throw new Error(`No embedded default config found in ${binary}`);
let end = start;
// The embedded file is plain text; it ends where the text does.
for (; end < bytes.length; end++) {
	const code = bytes.charCodeAt(end);
	if (code === 0 || code < 9 || (code > 13 && code < 32) || code > 126) break;
}
const config = bytes.slice(start, end);
if (!/^title = "gitleaks config"$/m.test(config) || !config.includes("[[rules]]")) throw new Error("The embedded text is not gitleaks' default config");

// The global allowlist's `paths = [ ... ]` holds only quoted regexes, one a line, ending with a line that is just `]`.
const paths = /^paths = \[\n(?:    '''.*''',\n)+\]\n/m;
if (!paths.test(config)) throw new Error("gitleaks' global path allowlist has changed shape; update this script");
// A function, not a string: a replacement string would read the "$'" in the regex as a pattern.
// The global allowlist is written in the newer `[[allowlists]]` form, which gitleaks reads the same way
// and which lets Porchlight add one of its own (gitleaks refuses the older form beside it).
const rules = config
	.replace(paths, () => "paths = [\n    '''(?:^|/)\\.git$''',\n]\n")
	.replace(/^# TODO: change to \[\[allowlists\]\]\n\[allowlist\]$/m, () => "[[allowlists]]");
if (!/^\[\[allowlists\]\]$/m.test(rules) || /^\[allowlist\]$/m.test(rules)) throw new Error("gitleaks' global allowlist header has changed shape; update this script");
const count = (rules.match(/^\[\[rules\]\]$/gm) ?? []).length;

const header = `# gitleaks' built-in rules, from gitleaks ${version}, with its global path allowlist reduced to .git.
# Generated by scripts/vendor-gitleaks-rules.mjs; do not edit by hand. ${count} rules.
#
# gitleaks' default config skips whole files by name (lockfiles, go.sum, *.svg, *.pdf, bootstrap*.js,
# venv/lib and more), so a key committed in one was never reported. Porchlight reads every file a
# repository holds and lets triage rank what it finds (invariant 10). The value allowlists (placeholders
# such as \${VAR}, true/false, stopwords) are kept as gitleaks ships them.
#
`;
// Named gitleaks.toml, as gitleaks names its own: one rule's pattern is a literal that matches itself, and
// gitleaks' default allowlist (which this repository's pre-commit hook uses) skips files of that name.
const out = fileURLToPath(new URL("../cli/src/repos/gitleaks.toml", import.meta.url));
writeFileSync(out, header + rules.replace(/\n+$/, "\n"));
console.log(`Wrote ${out}: ${count} rules from gitleaks ${version}`);
